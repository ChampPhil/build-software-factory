import { describe, it, expect, beforeAll } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { findReverts, findFixCommits, findProseRules, mineRepo, PROSE_FILES } from "../src/commands/mine-repo.js";

describe("findProseRules", () => {
  let root: string;

  beforeAll(() => {
    root = mkdtempSync(join(tmpdir(), "prose-"));
    writeFileSync(
      join(root, "AGENTS.md"),
      [
        "# Conventions",
        "",
        "Always put the migration behind an explicit command.",
        "This project uses Postgres.",
        "Never commit generated files.",
        "- Prefer the existing helper over a new one",
        "",
        "<!-- BEGIN: generated by next dev -->",
        "Always run `next build` before committing.",
        "<!-- END: generated by next dev -->",
        "",
        "```sh",
        "# never do this in a script",
        "rm -rf /",
        "```",
        "",
        "Do not use `any` in new code.",
      ].join("\n"),
    );
    writeFileSync(join(root, "CONTRIBUTING.md"), "You must run the tests before opening a PR.\n");
  });

  it("finds rule-shaped sentences", () => {
    const rules = findProseRules(root).map((r) => r.text);
    expect(rules).toContain("Always put the migration behind an explicit command.");
    expect(rules).toContain("Never commit generated files.");
    expect(rules).toContain("Prefer the existing helper over a new one");
    expect(rules).toContain("Do not use `any` in new code.");
  });

  it("ignores sentences that merely describe something", () => {
    expect(findProseRules(root).map((r) => r.text)).not.toContain("This project uses Postgres.");
  });

  it("skips generated blocks, which are a framework's rules and not the team's", () => {
    // `next dev` maintains regions in AGENTS.md. Mining those would file
    // Next's instructions as this team's conventions.
    const rules = findProseRules(root).map((r) => r.text);
    expect(rules.some((r) => r.includes("next build"))).toBe(false);
  });

  it("skips code blocks, which are examples", () => {
    expect(findProseRules(root).some((r) => r.text.includes("rm -rf"))).toBe(false);
  });

  it("reads every conventions file it knows, and records where each rule came from", () => {
    const rules = findProseRules(root);
    const files = new Set(rules.map((r) => r.file));
    expect(files).toContain("AGENTS.md");
    expect(files).toContain("CONTRIBUTING.md");
    for (const r of rules) expect(r.line).toBeGreaterThan(0);
  });

  it("knows about the files teams actually use", () => {
    for (const f of ["AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md", ".cursorrules"]) {
      expect(PROSE_FILES).toContain(f);
    }
  });

  it("finds nothing in a repo with no conventions written down", () => {
    expect(findProseRules(mkdtempSync(join(tmpdir(), "bare-")))).toHaveLength(0);
  });
});

describe("findReverts and findFixCommits", () => {
  let root: string;

  beforeAll(() => {
    root = mkdtempSync(join(tmpdir(), "gitmine-"));
    const g = (...args: string[]): string =>
      execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
    g("init", "-q");
    g("config", "user.email", "t@example.com");
    g("config", "user.name", "t");

    mkdirSync(join(root, "lib"), { recursive: true });
    writeFileSync(join(root, "lib/a.ts"), "export const a = 1;\n");
    g("add", "-A");
    g("commit", "-qm", "add the invoice total");

    const first = g("rev-parse", "HEAD").trim();

    writeFileSync(join(root, "lib/a.ts"), "export const a = 2;\n");
    g("add", "-A");
    g("commit", "-qm", "fix: the invoice total was off by one");

    writeFileSync(join(root, "lib/b.ts"), "export const b = 1;\n");
    g("add", "-A");
    g("commit", "-qm", "add a thing");
    g("revert", "--no-edit", g("rev-parse", "HEAD").trim());

    expect(first).toMatch(/^[0-9a-f]{40}$/);
  });

  it("finds a revert and the commit it reverted", async () => {
    const reverts = await findReverts(root);
    expect(reverts).toHaveLength(1);
    expect(reverts[0]?.reverted).toMatch(/^[0-9a-f]{7,40}$/);
    expect(reverts[0]?.files).toContain("lib/b.ts");
  });

  it("finds a fix that landed soon after the code it fixed", async () => {
    // The window is what makes this a signal: a fix to code written last week
    // got through review; a fix to code from a year ago is maintenance.
    const fixes = await findFixCommits(root);
    expect(fixes).toHaveLength(1);
    expect(fixes[0]?.subject).toContain("off by one");
    expect(fixes[0]?.fixes.length).toBeGreaterThan(0);
  });

  it("ignores a fix to code older than the window", async () => {
    // Backdated, because the whole point is the gap between the two commits
    // and a test repo builds them seconds apart.
    const old = mkdtempSync(join(tmpdir(), "oldfix-"));
    const g = (args: string[], date?: string): string =>
      execFileSync("git", args, {
        cwd: old,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
        env: date === undefined
          ? process.env
          : { ...process.env, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date },
      });
    g(["init", "-q"]);
    g(["config", "user.email", "t@example.com"]);
    g(["config", "user.name", "t"]);
    writeFileSync(join(old, "a.ts"), "export const a = 1;\n");
    g(["add", "-A"]);
    g(["commit", "-qm", "add a"], "2026-01-01T00:00:00Z");
    writeFileSync(join(old, "a.ts"), "export const a = 2;\n");
    g(["add", "-A"]);
    g(["commit", "-qm", "fix: a was wrong"], "2026-06-01T00:00:00Z");

    // Five months apart: maintenance, not something that got through review.
    expect(await findFixCommits(old, 3650, 14)).toHaveLength(0);
    // A window wide enough to span it finds the pair, so the filter is what
    // excluded it rather than the search finding nothing.
    expect(await findFixCommits(old, 3650, 400)).toHaveLength(1);
  });

  it("says nothing rather than failing where there is no git history", async () => {
    const bare = mkdtempSync(join(tmpdir(), "nogit-"));
    expect(await findReverts(bare)).toHaveLength(0);
    expect(await findFixCommits(bare)).toHaveLength(0);
  });

  it("expresses all three sources in the shape the clustering pass reads", async () => {
    writeFileSync(join(root, "AGENTS.md"), "Never commit generated files.\n");
    const mining = await mineRepo(root);
    const sources = new Set(mining.asCorrections.map((c) => c.source));
    expect(sources).toContain("revert");
    expect(sources).toContain("prose_rule");
    // "fix: a was wrong" is evidence. It is not admitted as a correction
    // until a classifier quotes a rule out of it.
    expect(sources.has("fix_commit")).toBe(false);
    expect(mining.fixes.length).toBeGreaterThan(0);
    // A revert is a decision already taken, so it does not go through the
    // classifier that scores a chat turn.
    const revert = mining.asCorrections.find((c) => c.source === "revert");
    expect(revert?.confidence).toBeGreaterThan(0.8);
  });
});
